export function isEnglishLearningWord(text: string): boolean {
  return /^[a-zA-Z]+(?:[-'][a-zA-Z]+)*$/.test(text.trim());
}

export function buildAiLearningTask(text: string, category: AiLearningCategory): string {
  return [
    `目标单词：${text.trim()}`,
    ...learningInstructions[category],
    "正文只写纯文本，使用 1.、2.、3. 编号组织阅读段落，每组之间用空行分隔。不要使用 Markdown 标记、表格、HTML 标签或代码块，不要额外写总标题。",
  ].join("\n");
}
